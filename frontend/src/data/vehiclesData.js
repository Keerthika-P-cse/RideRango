export const getPopularVehicles = () => {
  return vehiclesData.filter((v) => v.featured)
}

export const getCategories = () => {
  return categoriesData
}

export const getVehicleById = (id) => {
  if (!id) return null
  return vehiclesData.find((v) => String(v.id) === String(id)) || null
}

export const getVehiclesByCategory = (categorySlug) => {
  if (!categorySlug || categorySlug === 'all') return vehiclesData
  const norm = categorySlug.toLowerCase()
  return vehiclesData.filter((v) => {
    if (norm === 'scooties' || norm === 'scooters') {
      return v.category === 'scooties' || v.category === 'scooters'
    }
    if (norm === 'utility' || norm === 'commercial') {
      return v.category === 'utility' || v.category === 'commercial'
    }
    return v.category === norm
  })
}

export const getDistinctBrands = (categorySlug = null) => {
  const list = getVehiclesByCategory(categorySlug)
  return [...new Set(list.map((v) => v.brand))].sort()
}
